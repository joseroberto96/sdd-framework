# ----------------------------------------------------------- Clasificación


def _nfc(value: str) -> str:
    return unicodedata.normalize("NFC", value)


def classify_first_message(text: str) -> tuple[str, str]:
    """('comando', nombre) o ('texto_libre', '') para el primer mensaje humano."""
    body = text.strip()
    match = re.search(r"<command-name>\s*/?([^<\s]+)\s*</command-name>", body)
    if match:
        return "comando", _nfc(match.group(1))
    if "## My request:" in body:
        body = body.split("## My request:", 1)[1].strip()
    body = re.sub(r"^(?:<ide_[a-z_]+>.*?</ide_[a-z_]+>\s*)+", "", body, flags=re.DOTALL).strip()
    match = re.match(r"^\[\$(?:source-command-)?([\w-]+)\]", body)
    if match:
        return "comando", _nfc(match.group(1))
    match = re.match(r"^/([\w:.-]+)", body)
    if match:
        return "comando", _nfc(match.group(1))
    return "texto_libre", ""


def _claude_text(content: Any) -> str:
    if isinstance(content, str):
        return content
    parts = []
    for block in content or []:
        if isinstance(block, dict) and block.get("type") == "text":
            piece = str(block.get("text") or "")
            if not piece.lstrip().startswith("<system-reminder"):
                parts.append(piece)
    return "\n".join(parts)


def is_human_message(obj: dict[str, Any]) -> bool:
    """True si la entrada `user` de Claude es un mensaje humano real (ver docstring)."""
    if obj.get("type") != "user" or obj.get("isSidechain") or obj.get("isMeta") or obj.get("isCompactSummary"):
        return False
    message = obj.get("message") or {}
    content = message.get("content")
    if isinstance(content, list) and any(isinstance(b, dict) and b.get("type") == "tool_result" for b in content):
        return False
    origin = obj.get("origin")
    if isinstance(origin, dict) and origin.get("kind") not in (None, "human"):
        return False
    text = _claude_text(content).strip()
    if not text or text.startswith(NON_HUMAN_PREFIXES):
        return False
    match = re.search(r"<command-name>\s*/?([^<\s]+)\s*</command-name>", text)
    if match and _nfc(match.group(1)) in LOCAL_COMMANDS:
        return False
    return True


# ----------------------------------------------------------------- Lectores


def _assistant_text(obj: dict[str, Any]) -> str | None:
    message = obj.get("message") or {}
    if message.get("model") == "<synthetic>":
        return None
    parts = [
        str(b.get("text") or "")
        for b in (message.get("content") or [])
        if isinstance(b, dict) and b.get("type") == "text" and str(b.get("text") or "").strip()
    ]
    return "\n".join(parts) if parts else None


def read_claude_file(path: Path, projects: list[str] | None) -> Session | None:
    session = Session("claude", path.stem)
    last: tuple[str, str, str | None] | None = None  # (msg_id, ts, texto|None)
    seen_cwd = False
    order = 0
    first_human = False
    for obj in sc._iter_json(path):
        if not seen_cwd and obj.get("cwd"):
            session.cwd = str(obj["cwd"])
            seen_cwd = True
            if projects and not any(sc._cwd_matches(session.cwd, p) for p in projects):
                return None
        kind = obj.get("type")
        if obj.get("isSidechain"):
            continue
        if kind == "assistant":
            message = obj.get("message") or {}
            if message.get("model") == "<synthetic>":
                continue
            last = (str(message.get("id") or obj.get("uuid") or ""), str(obj.get("timestamp") or ""), _assistant_text(obj))
        elif kind == "user" and is_human_message(obj):
            if not first_human:
                first_human = True
                session.start = str(obj.get("timestamp") or "")
                session.first_kind, session.first_command = classify_first_message(_claude_text(obj["message"].get("content")))
            if last is not None:
                if last[2]:
                    order += 1
                    session.cierres.append(Cierre("claude", path.stem, session.cwd, last[1], last[0], last[2], False, order))
                else:
                    session.turnos_sin_texto_final += 1
            last = None
    if projects and not seen_cwd:
        return None
    if last is not None and last[2]:
        order += 1
        session.cierres.append(Cierre("claude", path.stem, session.cwd, last[1], last[0], last[2], True, order))
    elif last is not None:
        session.turnos_sin_texto_final += 1
    return session


def _codex_user_text(item: dict[str, Any]) -> str:
    return "".join(str(b.get("text") or "") for b in item.get("content") or [] if isinstance(b, dict))


def read_codex_file(path: Path, projects: list[str] | None) -> Session | None:
    rows = sc._iter_json(path)
    first = next(rows, None)
    meta = (first or {}).get("payload") if first and first.get("type") == "session_meta" else None
    if not isinstance(meta, dict) or meta.get("thread_source") in CODEX_IGNORED_SOURCES:
        return None
    cwd = str(meta.get("cwd") or "")
    if projects and not any(sc._cwd_matches(cwd, p) for p in projects):
        return None
    sid = str(meta.get("session_id") or meta.get("id") or path.stem)
    session = Session("codex", sid, cwd=cwd)
    order = 0
    for obj in rows:
        payload = obj.get("payload")
        if obj.get("type") != "event_msg" or not isinstance(payload, dict):
            continue
        ptype = payload.get("type")
        if ptype == "item_completed" and session.first_kind == "sin_mensaje":
            item = payload.get("item") or {}
            if item.get("type") == "UserMessage":
                text = _codex_user_text(item)
                if text.strip() and not text.lstrip().startswith(CODEX_INJECTED_PREFIXES):
                    session.start = str(obj.get("timestamp") or "")
                    session.first_kind, session.first_command = classify_first_message(text)
        elif ptype == "task_complete":
            message = payload.get("last_agent_message")
            if isinstance(message, str) and message.strip():
                order += 1
                session.cierres.append(Cierre(
                    "codex", sid, cwd, str(obj.get("timestamp") or ""),
                    str(payload.get("turn_id") or f"{path.stem}:{order}"), message, False, order,
                ))
    if session.cierres:
        session.cierres[-1].fin_de_sesion = True
    return session


def collect_sessions(agent: str, claude_dir: Path, codex_home: Path, projects: list[str] | None,
                     since: datetime | None) -> list[Session]:
    sessions: list[Session] = []
    if agent in ("claude", "all") and claude_dir.is_dir():
        files = []
        for path in claude_dir.glob("*/*.jsonl"):
            try:
                mtime = path.stat().st_mtime
            except OSError:
                continue
            if since and datetime.fromtimestamp(mtime, tz=timezone.utc) < since:
                continue
            files.append((mtime, path))
        for _, path in sorted(files):
            session = read_claude_file(path, projects)
            if session:
                sessions.append(session)
    if agent in ("codex", "all") and codex_home.is_dir():
        paths = sorted({p for sub in ("sessions", "archived_sessions") for p in (codex_home / sub).rglob("rollout-*.jsonl")})
        for path in paths:
            session = read_codex_file(path, projects)
            if session:
                sessions.append(session)
    return dedupe_sessions(sessions)


def dedupe_sessions(sessions: list[Session]) -> list[Session]:
    """Un cierre por id de mensaje; gana la última aparición (sesiones en orden de lectura)."""
    owner: dict[tuple[str, str], tuple[int, int]] = {}
    for si, session in enumerate(sessions):
        for ci, cierre in enumerate(session.cierres):
            owner[(cierre.agent, cierre.msg_id)] = (si, ci)
    for si, session in enumerate(sessions):
        session.cierres = [c for ci, c in enumerate(session.cierres) if owner[(c.agent, c.msg_id)] == (si, ci)]
    return sessions


# --------------------------------------------------------------- Medición


def _in_window(ts: str, since: datetime | None, until: datetime | None) -> bool:
    if not since and not until:
        return True
    moment = sc._ts(ts)
    if moment is None:
        return False
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=timezone.utc)
    return not ((since and moment < since) or (until and moment >= until))


def _percentile(values: list[int], pct: float) -> int:
    ordered = sorted(values)
    return ordered[max(0, math.ceil(pct * len(ordered)) - 1)]


@dataclass
class Evaluated:
    cierre: Cierre
    report: tc.TurnCloseReport
    projects: list[str]

    @property
    def codes(self) -> list[str]:
        return [d.code for d in self.report.defects]

    @property
    def valid(self) -> bool:
        return tc.is_valid(self.report.defects)


def evaluate(sessions: list[Session], manifest: dict[str, Any], projects: list[str],
             since: datetime | None, until: datetime | None) -> tuple[list[Evaluated], dict[tuple[str, str], Session]]:
    evaluated: list[Evaluated] = []
    kept: dict[tuple[str, str], Session] = {}
    for session in sessions:
        matches = [p for p in projects if sc._cwd_matches(session.cwd, p)] if projects else [ALL_PROJECTS]
        if not matches:
            continue
        start = session.start or (session.cierres[0].ts if session.cierres else "")
        if _in_window(start, since, until):
            kept[(session.agent, session.session_id)] = session
        for cierre in session.cierres:
            if not _in_window(cierre.ts, since, until):
                continue
            report = tc.analyze_turn_close(cierre.text, manifest=manifest, mode="live")
            evaluated.append(Evaluated(cierre, report, matches))
    return evaluated, kept


def compute_metrics(items: list[Evaluated], sessions: list[Session]) -> dict[str, Any]:
    total = len(items)
    valid = sum(1 for e in items if e.valid)
    by_code = {code: 0 for code in tc.ALL_CODES}
    for e in items:
        for code in set(e.codes):
            by_code[code] += 1
    forms: Counter[str] = Counter()
    commands: Counter[str] = Counter()
    adornos: Counter[str] = Counter()
    pairs: Counter[str] = Counter()
    verbs: Counter[str] = Counter()
    lengths: list[int] = []
    with_model = 0
    ciclo_lines = 0
    ciclo_decision = 0
    by_agent: dict[str, dict[str, int]] = {}
    for e in items:
        slot = by_agent.setdefault(e.cierre.agent, {"cierres": 0, "validos": 0, "fin_de_sesion": 0})
        slot["cierres"] += 1
        slot["validos"] += int(e.valid)
        slot["fin_de_sesion"] += int(e.cierre.fin_de_sesion)
        parts = e.report.parts
        if parts.model_line:
            with_model += 1
            if parts.model_ok:
                pairs[f"{parts.modelo} · {parts.esfuerzo}"] += 1
        if not parts.found:
            continue
        forms[parts.form] += 1
        for a in parts.adornos:
            adornos[a] += 1
        if parts.form in (tc.FORM_COMMAND, tc.FORM_CICLO_FASE):
            commands["/" + parts.command] += 1
            if parts.instruction:
                lengths.append(len(parts.instruction))
            if parts.command == "ciclo":
                ciclo_lines += 1
                verbs[tc.fold(parts.instruction.split()[0].strip(".,;:")) if parts.instruction else "(vacía)"] += 1
                if tc.DECISION_EN_CICLO in e.codes:
                    ciclo_decision += 1
        elif parts.form == tc.FORM_NINGUNO:
            commands["ninguno"] += 1
        elif parts.form == tc.FORM_DECISION:
            commands["decisión"] += 1
    openers: Counter[str] = Counter()
    kinds: Counter[str] = Counter()
    arrancar = 0
    arrancar_to_ciclo = 0
    for session in sessions:
        kinds[session.first_kind] += 1
        if session.first_kind == "comando":
            openers["/" + session.first_command] += 1
        if session.first_kind == "comando" and session.first_command == "arrancar":
            arrancar += 1
            if session.cierres:
                first = tc.extract_close_parts(session.cierres[0].text, manifest={})
                if first.found and first.command == "ciclo":
                    arrancar_to_ciclo += 1
    return {
        "cierres_total": total,
        "cierres_validos": valid,
        "cierres_invalidos": total - valid,
        "porcentaje_validos": round(100 * valid / total, 1) if total else 0.0,
        "cierres_fin_de_sesion": sum(1 for e in items if e.cierre.fin_de_sesion),
        "por_agente": by_agent,
        "defectos_por_codigo": by_code,
        "sin_siguiente": by_code[tc.SIN_SIGUIENTE],
        "formato_heredado": by_code[tc.FORMATO_HEREDADO],
        "cierres_con_aviso": sum(1 for e in items if any(d.severity == tc.SEVERITY_WARNING for d in e.report.defects)),
        "formas": dict(forms.most_common()),
        "adornos_markdown": dict(adornos),
        "comandos": dict(commands.most_common()),
        "ciclo": {
            "lineas": ciclo_lines,
            "decision_en_ciclo": ciclo_decision,
            "primer_verbo": dict(verbs.most_common()),
        },
        "modelo_esfuerzo": {"con_linea": with_model, "pares": dict(pairs.most_common())},
        "instruccion_longitud": {
            "n": len(lengths),
            "mediana": statistics.median(lengths) if lengths else 0,
            "p90": _percentile(lengths, 0.9) if lengths else 0,
            "maximo": max(lengths) if lengths else 0,
        },
        "sesiones": {
            "total": len(sessions),
            "primer_mensaje": dict(kinds),
            "comando_inicial": dict(openers.most_common()),
            "abren_con_arrancar": arrancar,
            "arrancar_primer_cierre_solo_ciclo": arrancar_to_ciclo,
            "turnos_sin_texto_final": sum(s.turnos_sin_texto_final for s in sessions),
        },
    }


def build_report(items: list[Evaluated], kept: dict[tuple[str, str], Session], projects: list[str]) -> dict[str, Any]:
    names = projects or [ALL_PROJECTS]
    per_project: dict[str, Any] = {}
    for name in names:
        group = [e for e in items if name in e.projects]
        sess = [s for s in kept.values() if (name == ALL_PROJECTS or sc._cwd_matches(s.cwd, name))]
        per_project[name] = compute_metrics(group, sess)
    return {
        "proyectos": per_project,
        "total": compute_metrics(items, list(kept.values())),
        "cierres": [
            {
                "agente": e.cierre.agent,
                "sesion": e.cierre.session,
                "proyectos": e.projects,
                "ts": e.cierre.ts,
                "fin_de_sesion": e.cierre.fin_de_sesion,
                "valido": e.valid,
                "codigos": e.codes,
                "forma": e.report.parts.form,
                "comando": e.report.parts.command,
                "linea_de_cierre": e.report.parts.raw,
            }
            for e in items
        ],
    }


