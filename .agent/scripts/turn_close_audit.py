@dataclass
class Cierre:
    agent: str
    session: str
    cwd: str
    ts: str
    msg_id: str
    text: str
    fin_de_sesion: bool = False
    order: int = 0


@dataclass
class Session:
    agent: str
    session_id: str
    cwd: str = ""
    start: str = ""
