def _parse_day(value: str | None, flag: str) -> datetime | None:
    if not value:
        return None
    try:
        return datetime.strptime(value, "%Y-%m-%d").replace(tzinfo=timezone.utc)
    except ValueError:
        raise SystemExit(_usage_error(f"{flag} inválido: {value!r} (usa YYYY-MM-DD)"))


def _usage_error(message: str) -> int:
    print(message, file=sys.stderr)
    return 2


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Auditoría del cierre de turno sobre transcripciones (solo lectura).")
    parser.add_argument("--agent", choices=("claude", "codex", "all"), default="all")
    parser.add_argument("--project", action="append", default=[], metavar="RUTA",
                        help="ruta real del proyecto (repetible); se compara con el cwd de la transcripción")
    parser.add_argument("--since", help="solo cierres desde YYYY-MM-DD (UTC, inclusive)")
    parser.add_argument("--until", help="solo cierres hasta YYYY-MM-DD (UTC, exclusivo)")
    parser.add_argument("--json", action="store_true", help="salida JSON")
    parser.add_argument("--claude-dir", default="~/.claude/projects")
    parser.add_argument("--codex-home", default=os.environ.get("CODEX_HOME", "~/.codex"))
    parser.add_argument("--manifest", help="ruta del manifest.json (por defecto el del repo del script)")
    parser.add_argument("--root", help="raíz del repo para --templates y --vocabulary (por defecto, el repo del script)")
    parser.add_argument("--templates", action="store_true",
                        help="valida las plantillas de cierre de .agent/workflows (no lee transcripciones)")
    parser.add_argument("--vocabulary", action="store_true",
                        help="cuenta vocabulario retirado en las superficies activas (no lee transcripciones)")
    return parser


def main(argv: list[str] | None = None) -> int:
    try:
        args = build_parser().parse_args(argv)
    except SystemExit as exc:
        return int(exc.code) if isinstance(exc.code, int) else 2
    try:
        since = _parse_day(args.since, "--since")
        until = _parse_day(args.until, "--until")
    except SystemExit as exc:
        return int(exc.code)
    root = Path(args.root).expanduser().resolve() if args.root else REPO_ROOT
    manifest_path = Path(args.manifest).expanduser() if args.manifest else root / ".agent" / "workflows" / "manifest.json"
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return _usage_error(f"No se pudo leer el manifest {manifest_path}: {exc}")
    if not isinstance(manifest, dict) or not isinstance(manifest.get("commands"), list):
        return _usage_error(f"El manifest {manifest_path} no tiene la forma esperada (clave 'commands').")

    if args.templates or args.vocabulary:
        result: dict[str, Any] = {}
        texts: list[str] = []
        if args.templates:
            result["plantillas"] = audit_templates(root, manifest)
            texts.append(format_templates(result["plantillas"]))
        if args.vocabulary:
            result["vocabulario"] = audit_vocabulary(root)
            texts.append(format_vocabulary(result["vocabulario"]))
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else "\n\n".join(texts))
        return 0

    projects = [os.path.expanduser(p) for p in args.project]
    sessions = collect_sessions(
        args.agent, Path(args.claude_dir).expanduser(), Path(args.codex_home).expanduser(), projects or None, since,
    )
    items, kept = evaluate(sessions, manifest, projects, since, until)
    report = build_report(items, kept, projects)
    report["parametros"] = {
        "agente": args.agent, "proyectos": projects, "desde": args.since, "hasta": args.until,
        "manifest": str(manifest_path),
    }
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        print(format_report(report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
