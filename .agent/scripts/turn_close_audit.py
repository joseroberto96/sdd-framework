def _fmt_counts(counts: dict[str, int], limit: int | None = None) -> list[str]:
    items = list(counts.items())[:limit] if limit else list(counts.items())
    return [f"    {k:<28} {v}" for k, v in items] or ["    (ninguno)"]


def format_group(name: str, m: dict[str, Any]) -> str:
    out = [f"== {name} =="]
    total = m["cierres_total"]
    out.append(f"Cierres: {total}   válidos: {m['cierres_validos']} ({m['porcentaje_validos']}%)   "
               f"sin Siguiente: {m['sin_siguiente']}   formato heredado: {m['formato_heredado']}   "
               f"con aviso: {m['cierres_con_aviso']}   fin de sesión: {m['cierres_fin_de_sesion']}")
    out.append("  Defectos por código (cierres afectados):")
    out += [f"    {c:<28} {n}" for c, n in m["defectos_por_codigo"].items() if n]
    if not any(m["defectos_por_codigo"].values()):
        out.append("    (ninguno)")
    out.append("  Comandos en la línea de cierre:")
    out += _fmt_counts(m["comandos"])
    ciclo = m["ciclo"]
    out.append(f"  /ciclo: {ciclo['lineas']} líneas, {ciclo['decision_en_ciclo']} en DECISION_EN_CICLO; primer verbo:")
    out += _fmt_counts(ciclo["primer_verbo"], 10)
    me = m["modelo_esfuerzo"]
    out.append(f"  Línea Modelo · Esfuerzo: {me['con_linea']} de {total}; pares:")
    out += _fmt_counts(me["pares"])
    il = m["instruccion_longitud"]
    out.append(f"  Longitud de la instrucción (n={il['n']}): mediana {il['mediana']}, p90 {il['p90']}, máximo {il['maximo']}")
    if m["adornos_markdown"]:
        out.append("  Adornos markdown tolerados: " + ", ".join(f"{k}={v}" for k, v in m["adornos_markdown"].items()))
    s = m["sesiones"]
    out.append(f"  Sesiones: {s['total']}   primer mensaje: {s['primer_mensaje']}   "
               f"abren con /arrancar: {s['abren_con_arrancar']} "
               f"(su primer cierre solo reenvía a /ciclo: {s['arrancar_primer_cierre_solo_ciclo']})   "
               f"turnos sin texto final: {s['turnos_sin_texto_final']}")
    out.append("    comando inicial:")
    out += _fmt_counts(s["comando_inicial"], 10)
    return "\n".join(out)


def format_report(report: dict[str, Any]) -> str:
    blocks = [format_group(name, m) for name, m in report["proyectos"].items()]
    if len(report["proyectos"]) != 1:
        blocks.append(format_group("TOTAL", report["total"]))
    return "\n\n".join(blocks)


def format_templates(data: dict[str, Any]) -> str:
    out = [
        "== Plantillas de cierre en .agent/workflows ==",
        f"Líneas defectuosas: {data['lineas_defectuosas']} de {data['lineas_plantilla']}   "
        f"workflows afectados: {data['workflows_afectados']} de {data['workflows_con_plantilla']} con plantilla "
        f"({data['workflows_total']} workflows)   menciones en prosa omitidas: {data['menciones_en_prosa']}",
        "  Defectos por código:",
    ]
    out += [f"    {c:<28} {n}" for c, n in data["defectos_por_codigo"].items()] or ["    (ninguno)"]
    out.append("  Detalle:")
    out += [f"    {d['fichero']}:{d['linea']}  {','.join(d['codigos'])}" for d in data["defectuosas"]] or ["    (ninguno)"]
    return "\n".join(out)


def format_vocabulary(data: dict[str, Any]) -> str:
    out = [
        "== Vocabulario retirado en superficies activas ==",
        f"Apariciones: {data['apariciones_total']} en {data['superficies']} ficheros revisados",
    ]
    for term, info in data["terminos"].items():
        out.append(f"  {term!r}: {info['total']}")
        out += [f"      {rel}: {n}" for rel, n in info["ficheros"].items()]
    return "\n".join(out)


