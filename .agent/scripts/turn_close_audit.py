@dataclass
class TemplateLine:
    file: str
    line: int
    text: str
    codes: list[str]

    @property
    def defective(self) -> bool:
        return bool(self.codes)


_template_candidate = tc.template_candidate  # una sola definición (turn_close.py)


def audit_templates(root: Path, manifest: dict[str, Any]) -> dict[str, Any]:
    wf_dir = root / ".agent" / "workflows"
    files = sorted(wf_dir.glob("*.md")) if wf_dir.is_dir() else []
    lines: list[TemplateLine] = []
    mentions: list[dict[str, Any]] = []
    for path in files:
        rel = str(path.relative_to(root))
        try:
            content = path.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            continue
        text_doc = "\n".join(content)
        mentions.extend({"fichero": rel, "linea": n} for n in tc.template_mentions(text_doc))
        for finding in tc.scan_templates(text_doc, manifest=manifest):
            lines.append(TemplateLine(rel, finding.line, finding.text, finding.codes))
    with_template = sorted({t.file for t in lines})
    affected = sorted({t.file for t in lines if t.defective})
    by_code: Counter[str] = Counter(c for t in lines for c in t.codes)
    return {
        "workflows_total": len(files),
        "workflows_con_plantilla": len(with_template),
        "workflows_afectados": len(affected),
        "lineas_plantilla": len(lines),
        "lineas_defectuosas": sum(1 for t in lines if t.defective),
        "menciones_en_prosa": len(mentions),
        "defectos_por_codigo": dict(by_code.most_common()),
        "defectuosas": [
            {"fichero": t.file, "linea": t.line, "codigos": t.codes, "texto": t.text} for t in lines if t.defective
        ],
        "menciones": mentions,
    }


# -------------------------------------------------------------- Vocabulario


def vocabulary_surfaces(root: Path) -> list[Path]:
    found: set[Path] = set()
    for pattern in ("*.md", "llms.txt"):
        found.update(p for p in root.glob(pattern) if p.is_file())
    for rel, recursive in VOCAB_SURFACE_DIRS:
        base = root / rel
        if not base.is_dir():
            continue
        iterator = base.rglob("*") if recursive else base.glob("*.md")
        found.update(p for p in iterator if p.is_file() and p.suffix in VOCAB_SUFFIXES)
    for rel in VOCAB_SURFACE_FILES:
        if (root / rel).is_file():
            found.add(root / rel)
    result = []
    for path in sorted(found):
        parts = path.relative_to(root).parts
        if path.name in VOCAB_EXCLUDED_NAMES or parts[0] in VOCAB_EXCLUDED_DIRS:
            continue
        result.append(path)
    return result


def audit_vocabulary(root: Path) -> dict[str, Any]:
    surfaces = vocabulary_surfaces(root)
    terms: dict[str, dict[str, Any]] = {t: {"total": 0, "ficheros": {}} for t in RETIRED_TERMS}
    for path in surfaces:
        try:
            content = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        rel = str(path.relative_to(root))
        for term in RETIRED_TERMS:
            count = content.count(term)
            if count:
                terms[term]["total"] += count
                terms[term]["ficheros"][rel] = count
    return {
        "superficies": len(surfaces),
        "apariciones_total": sum(t["total"] for t in terms.values()),
        "terminos": terms,
    }


