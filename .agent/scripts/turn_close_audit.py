#!/usr/bin/env python3
"""Auditoría de solo lectura del cierre de turno sobre transcripciones reales.

Aplica `turn_close.validate_turn_close` (la única definición del contrato) a lo
que los agentes emitieron de verdad y mide cuántos cierres cumplen el contrato
de `.agent/skills/decision_translation_core.md`. Es un medidor, no un gate:
termina con código 0 si la medición acaba (2 con argumentos inválidos). No
escribe nada fuera de stdout.

Fuentes
-------
- Claude Code: ``~/.claude/projects/<carpeta>/*.jsonl`` (solo el nivel superior:
  las transcripciones de subagentes viven en ``<sesión>/subagents/`` y no se
  auditan). El cierre de un turno es el último texto del asistente antes de cada
  mensaje humano real, y también el último texto del asistente al final de la
  transcripción (`fin_de_sesion: true`). Un turno cuya última entrada del
  asistente es solo una llamada a herramienta (interrumpido) no tiene cierre y se
  cuenta aparte como `turnos_sin_texto_final`.
- Codex: ``~/.codex/{sessions,archived_sessions}/**/rollout-*.jsonl``. El cierre
  es ``task_complete.last_agent_message`` de la sesión raíz (cada turno). Se
  ignoran los ficheros con ``thread_source`` ``subagent`` y ``guardian_review``
  (el criterio de `session_cost.py`) y, además, ``security_scan``: son ejecuciones
  automáticas sin builder, cuyo último mensaje es un informe, no un cierre.

Qué es un «mensaje humano real» en Claude Code
----------------------------------------------
Una entrada ``type: user`` que NO es: ``isSidechain``, ``isMeta`` (incluye las
expansiones de skills, «Continue from where you left off» y los hand-back de
subagentes), ``isCompactSummary``, un resultado de herramienta (``tool_result``),
una entrada con ``origin.kind`` distinto de ``human`` (``task-notification``,
``peer``), ni un texto que empiece por un recordatorio del sistema, una
notificación de tarea, el aviso/salida de un comando local (``/model``,
``/clear``, ...), «[Request interrupted by user» o «The app was quit while you
were working». Los comandos de skill (``<command-name>/ciclo</command-name>``),
los textos libres, los pegados (``<pasted_content>``) y las órdenes ``!`` del
usuario sí cuentan. Las transcripciones antiguas no traen ``origin``: ahí solo
actúan el resto de criterios. En Codex el mensaje humano es el primer
``item_completed`` de tipo ``UserMessage`` no inyectado.

Deduplicación: un mismo mensaje del asistente puede reaparecer (tras compactar o
reanudar); se cuenta una vez por id de mensaje (Claude) o ``turn_id`` (Codex),
quedándose con la última aparición.
"""

