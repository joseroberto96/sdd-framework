"""projections.py - Read-only Markdown/JSON projections of the state.

Paths are read from state_core at call time (state_core.CORE_FILE_PATH, etc.)
so tests can monkeypatch them. Every projection file carries the autogenerated
banner.
"""
from __future__ import annotations
import json
import re
import sys
import datetime
from pathlib import Path

import state_core
import turn_close

BANNER = "<!-- GENERADO AUTOMÁTICAMENTE - NO EDITAR A MANO -->"


class ProjectionGuardError(Exception):
    """Raised when render would overwrite a non-empty file lacking the banner."""


def _assert_safe_to_write(path) -> None:
    if path.exists():
        content = path.read_text(encoding="utf-8").strip()
        if content and BANNER not in content:
            raise ProjectionGuardError(
                f"{path} tiene contenido manual sin banner de autogenerado. "
                f"Ejecuta 'python3 .agent/scripts/state_manager.py import' antes de renderizar."
            )



def _atomic_write(path, content: str) -> None:
    """Escritura atómica de una proyección (C5 del triaje 2026-07-09): volcar a
    un temporal en el mismo directorio y os.replace() — un crash a mitad de
    render nunca deja una vista truncada."""
    import os
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    os.replace(tmp, path)



def _as_data(value) -> str:
    """Texto de origen externo (títulos de bugs, decisiones, punteros de
    sesión) proyectado como DATO, no como markdown crudo (triaje 2026-07-09):
    sin saltos de línea (no puede abrir bloques nuevos), sin headings que se
    conviertan en secciones del archivo, sin comentarios HTML/directivas.
    La fuente canónica (03_project_state.json) conserva el texto original."""
    text = " ".join(str(value).splitlines()).strip()
    while text.startswith("#"):
        text = text.lstrip("#").strip()
    return text.replace("<!--", "<! --").replace("-->", "-- >")


def _now_iso() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


NO_POINTER_ACTION = (
    "no hay siguiente paso registrado; pide el estado en una sesión nueva o usa /reconciliar"
)


def _session_pointer_values(session: dict) -> tuple[str, str, str]:
    """Validate and compose the only user-facing continuation line.

    ``next_command`` and ``next_action`` stay separate in canonical state;
    this is the sole projection layer that combines them.  The blocking
    sentinel gets an explicit separator so it cannot be mistaken for a
    runnable command with a natural-language suffix.

    Without any pointer (neither ``next_command`` nor ``next_action``) the line
    is the explicit ``ninguno`` form: the projection never invents work to do.
    A partial session with only ``next_action`` keeps composing with ``/ciclo``.
    """
    state_core.validate_session_pointer(session, root=state_core.WORKSPACE_ROOT)
    if "next_command" not in session and "next_action" not in session:
        next_command, next_action = "ninguno", NO_POINTER_ACTION
    else:
        next_action = _as_data(session.get("next_action", ""))
        next_command = _as_data(session.get("next_command", "/ciclo"))
    if next_command == "ninguno":
        next_line = f"Siguiente: ninguno — {next_action}"
    else:
        next_line = f"Siguiente: {next_command} {next_action}"
    return next_command, next_action, next_line


def _session_pointer_warning(next_line: str, root=None) -> str:
    """Aviso en cita si la línea compuesta no cumple el contrato de cierre.

    Usa el validador único (`turn_close`, modo ``live`` sobre la línea sola); cuentan los
    errores y, desde 5.3.2, los avisos de puntero largo o con prohibiciones (FW-402). Nunca
    lanza ni reescribe nada (un estado anterior debe seguir renderizando); si el
    manifest no se puede leer, no valida.
    """
    try:
        manifest_path = Path(root or state_core.WORKSPACE_ROOT) / ".agent" / "workflows" / "manifest.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if not isinstance(manifest, dict):
            return ""
        defects = turn_close.validate_turn_close(next_line, manifest=manifest, mode="live")
    except Exception:  # fail-open: sin manifest legible no se valida
        return ""
    codes = []
    for defect in defects:
        pointer = defect.code in (turn_close.INSTRUCCION_LARGA, turn_close.PROHIBICIONES)
        if (defect.severity == turn_close.SEVERITY_ERROR or pointer) and defect.code not in codes:
            codes.append(defect.code)
    if not codes:
        return ""
    return (
        "> Aviso: el siguiente paso registrado no cumple el contrato de cierre "
        f"({', '.join(codes)}). Corrígelo con `set_session_pointer`."
    )


def module_counts(state_data: dict) -> dict:
    """FW-275 (5.2.2): recuento visible. «Completado» es código cerrado por el
    agente; «usado» exige `work_tiers[mod].builder_use` (confirm_builder_use)."""
    modules = state_data.get("modules", {}) if isinstance(state_data.get("modules"), dict) else {}
    completed = list(modules.get("completed") or [])
    tiers = state_data.get("work_tiers", {}) if isinstance(state_data.get("work_tiers"), dict) else {}
    used = [
        mod for mod in completed
        if isinstance(tiers.get(mod), dict) and isinstance(tiers[mod].get("builder_use"), dict)
    ]
    counts = {
        "completed": len(completed),
        "builder_used": len(used),
        "pending": len(modules.get("pending") or []) + len(modules.get("in_progress") or []),
    }
    # PA-FW-037 (5.3.3): un módulo abandonado no es completado ni pendiente.
    # La clave solo aparece si hay alguno, para no envejecer el brief de los
    # proyectos que nunca abandonan un módulo.
    dropped = len(modules.get("dropped") or [])
    if dropped:
        counts["dropped"] = dropped
    return counts


def module_counts_line(state_data: dict) -> str:
    counts = module_counts(state_data)
    line = (
        f"Módulos: {counts['completed']} completados · {counts['builder_used']} usados por ti · "
        f"{counts['pending']} pendientes"
    )
    if counts.get("dropped"):
        line += f" · {counts['dropped']} retirados"
    return line


def _next_module_label(state_data: dict, sess: dict) -> str:
    """Próximo módulo de la sesión, sin anunciar uno abandonado (PA-FW-037).

    Un módulo `dropped` conserva sus work_tiers como histórico; sin este
    filtro el brief lo seguiría pintando como siguiente."""
    next_module = _as_data(sess.get("next_module", "pendiente de /scope-siguiente"))
    if isinstance(next_module, str) and (
        state_data.get("module_statuses", {}).get(next_module) == "dropped"
        or next_module in state_data.get("modules", {}).get("dropped", [])
    ):
        return "pendiente de /scope-siguiente"
    return next_module


def expected_session_brief(state_data: dict, *, generated_at: str | None = None) -> dict:
    """Construye los campos semánticos del brief desde el estado canónico.

    Mantener este cálculo separado permite que el doctor compare el JSON
    persistido sin renderizar ni escribir proyecciones. ``generated_at`` es el
    único campo deliberadamente no determinista: ``render`` solo reescribe el
    brief si cambia otro campo, así que es la hora del último cambio (FW-296).
    """
    project = state_data.get("project", "[NOMBRE_PROYECTO]")
    phase = state_data.get("current_phase", "phase_01")
    in_progress = state_data.get("modules", {}).get("in_progress", [])
    active_mod = in_progress[0] if in_progress else "ninguno"
    tier = state_data.get("work_tiers", {}).get(active_mod, {}).get("tier", "no clasificado")
    sess = state_data.get("session", {})
    if not isinstance(sess, dict):
        sess = {}
    _, next_action, _ = _session_pointer_values(sess)
    next_module = _next_module_label(state_data, sess)
    next_tier = state_data.get("work_tiers", {}).get(next_module, {}).get("tier")

    migrations = state_data.get("framework_migrations", {})
    migration_statuses = {
        migration_id: {
            "type": entry.get("type"),
            "status": entry.get("status"),
        }
        for migration_id, entry in migrations.items()
        if isinstance(entry, dict)
    } if isinstance(migrations, dict) else {}

    blockers: list[str] = []
    for bug in state_data.get("_bugs", []):
        if bug["status"] == "Abierto" and (
            bug["severity"] == "Crítico"
            or (bug["severity"] == "Mayor" and bug["affects_ac"])
        ):
            blockers.append(f"- ⚠️ {bug['id']} ({bug['severity']}) - {bug['description']}")
    for clarification in state_data.get("_clarifications", []):
        if clarification["status"] == "Abierta" and (
            clarification["blocks_start"]
            or clarification["blocks_implementation"]
            or clarification["blocks_closure"]
        ):
            blockers.append(
                f"- ⚠️ {clarification['id']} (Clarificación) - {clarification['question']}"
            )

    return {
        "generated_at": generated_at if generated_at is not None else _now_iso(),
        "project": project,
        "framework_mode": state_data.get("framework_mode", "template"),
        "current_phase": phase,
        "current_step": state_data.get("current_step", ""),
        "last_completed_step": _as_data(state_data.get("last_completed_step", "Ninguno")),
        "active_module": active_mod if active_mod != "ninguno" else None,
        "active_work_tier": tier if active_mod != "ninguno" else None,
        "next_module": next_module if next_tier else None,
        "next_work_tier": next_tier,
        "next_action": next_action,
        "framework_migrations": migration_statuses,
        "module_counts": module_counts(state_data),
        "open_blockers": [item.split(" - ")[0].replace("- ⚠️ ", "") for item in blockers]
        if blockers else [],
    }


def projection_semantic_diff(state_data: dict, brief: object) -> dict:
    """Devuelve diferencias semánticas entre estado y ``00_session_brief``."""
    if not isinstance(brief, dict):
        return {"brief": {"expected": "object", "actual": type(brief).__name__}}
    expected = expected_session_brief(state_data, generated_at=brief.get("generated_at"))
    actual = {key: value for key, value in brief.items() if key != "generated_at"}
    expected_without_time = {key: value for key, value in expected.items() if key != "generated_at"}
    diff: dict[str, dict] = {}
    # FW-275: un brief anterior a 5.2.2 no trae `module_counts`; es derivado y se
    # regenera en la siguiente mutación, así que su ausencia no es desfase.
    if "module_counts" not in actual:
        expected_without_time.pop("module_counts", None)
    for key in sorted(set(expected_without_time) | set(actual)):
        expected_value = expected_without_time.get(key)
        actual_value = actual.get(key)
        if expected_value != actual_value:
            diff[key] = {"expected": expected_value, "actual": actual_value}
    return diff


def render_core_markdown(
    state_data: dict,
    *,
    now_iso: str | None = None,
    workspace_root: Path | None = None,
) -> str:
    """Renderiza el contenido de core.md en memoria a partir del estado canónico."""
    project = state_data.get("project", "[NOMBRE_PROYECTO]")
    phase = state_data.get("current_phase", "phase_01")
    last_step = state_data.get("last_completed_step", "Ninguno")
    now_iso = now_iso if now_iso is not None else _now_iso()

    in_progress = state_data.get("modules", {}).get("in_progress", [])
    active_mod = in_progress[0] if in_progress else "ninguno"
    status = state_data.get("module_statuses", {}).get(active_mod, "not_started")
    tier = state_data.get("work_tiers", {}).get(active_mod, {}).get("tier", "no clasificado")

    last_step = _as_data(last_step)
    sess = state_data.get("session", {})
    if sess is None:
        sess = {}
    active_desc = _as_data(sess.get("active_module_description", "Módulo de trabajo activo."))
    # FW-095 (PA FW-043 reincidente): si la descripción registrada pertenece a
    # otro módulo (sello `described_module` de set_session_pointer), NO se
    # aplica al módulo activo actual — mostrar default + nota. Evita que
    # /arrancar guíe la sesión con la descripción del próximo módulo pegada
    # al módulo bloqueado.
    described = sess.get("described_module")
    if described is not None and described != active_mod:
        active_desc = (
            "Módulo de trabajo activo. (La descripción de sesión registrada "
            f"corresponde a `{described}` — actualizar con set_session_pointer "
            "o set_active_module.)"
        )
    # FW-215: la validación compartida ocurre antes de sanitizar/interpolar.
    # Así una forma heredada no puede ocultarse al convertirla en dato plano.
    next_command, next_action, next_line = _session_pointer_values(sess)
    next_warning = _session_pointer_warning(next_line, workspace_root)
    if next_warning:
        next_line = f"{next_warning}\n\n{next_line}"
    next_module = _next_module_label(state_data, sess)
    # 3.12.0: foco activo del builder. Si el campo no existe (proyectos
    # pre-3.12), la lectura devuelve None y la proyección muestra "sin foco"
    # — no rompe la retrocompatibilidad. Cuando el campo es string vacío o
    # None explícito, también "sin foco".
    raw_focus = state_data.get("active_focus")
    focus_label = raw_focus if isinstance(raw_focus, str) and raw_focus.strip() else "sin foco"
    # FW-039: cuando no hay módulo activo, el agente actúa sobre el PRÓXIMO módulo.
    # Resolver su tier canónico desde work_tiers (la verdad), para que un tier_2 no
    # se proyecte como "no clasificado" y el agente no se salte su rigor.
    next_tier = state_data.get("work_tiers", {}).get(next_module, {}).get("tier")
    if next_tier:
        next_module_block = (
            f"{next_module}\n\n"
            f"- **Tier de rigor**: `{next_tier}` (canónico desde `work_tiers`; "
            f"aplica su rigor antes de implementar)"
        )
    else:
        next_module_block = next_module
    # FW-095: la descripción del próximo módulo vive en su propio campo y se
    # proyecta en SU sección, nunca en la del módulo activo.
    next_module_desc = _as_data(sess.get("next_module_description", ""))
    if next_module_desc:
        next_module_block += f"\n\n- **Descripción**: {next_module_desc}"

    migrations = state_data.get("framework_migrations", {})
    migration_entries = [
        f"- {_as_data(migration_id)}: {_as_data(entry.get('status', ''))}"
        for migration_id, entry in sorted(migrations.items())
        if isinstance(entry, dict)
    ] if isinstance(migrations, dict) else []
    framework_migrations_block = "\n".join(migration_entries) if migration_entries else "[ninguna]"

    ws_root = workspace_root if workspace_root is not None else getattr(state_core, "WORKSPACE_ROOT", None)
    if ws_root is None:
        ws_root = state_core.find_workspace_root()
    acs_text = ""
    if active_mod != "ninguno":
        acs_path = ws_root / "_project" / "08_module_acceptance.md"
        if acs_path.exists():
            text = acs_path.read_text(encoding="utf-8")
            match = re.search(rf"(?mi)^##\s+.*?{re.escape(active_mod)}\b.*?\n", text)
            if match:
                start = match.end()
                next_h = re.search(r"(?mi)^##\s+", text[start:])
                acs_text = text[start : start + next_h.start()].strip() if next_h else text[start:].strip()
        if not acs_text:
            acs_text = "- [ ] Criterios pendientes de definir en 08_module_acceptance.md."
    else:
        acs_text = "[ninguno]"

    blockers = []
    for b in state_data.get("_bugs", []):
        if b["status"] == "Abierto" and (b["severity"] == "Crítico" or (b["severity"] == "Mayor" and b["affects_ac"])):
            blockers.append(f"- ⚠️ {b['id']} ({b['severity']}) - {b['description']}")
    for c in state_data.get("_clarifications", []):
        if c["status"] == "Abierta" and (c["blocks_start"] or c["blocks_implementation"] or c["blocks_closure"]):
            blockers.append(f"- ⚠️ {c['id']} (Clarificación) - {c['question']}")
    blockers_str = "\n".join(blockers) if blockers else "[ninguno]"

    # FW-225: modo mantenimiento. Solo se proyecta si el proyecto declaró su
    # ciclo de vida: los adoptantes que no lo usan conservan core.md intacto.
    lifecycle = state_data.get("lifecycle") if isinstance(state_data.get("lifecycle"), dict) else None
    changes = [c for c in (state_data.get("changes") or []) if isinstance(c, dict)]
    counts_line = module_counts_line(state_data).replace("Módulos:", "**Módulos**:", 1)
    lifecycle_line = ""
    change_section = ""
    if lifecycle:
        stage = _as_data(lifecycle.get("stage", "development"))
        lifecycle_line = f"\n- **Ciclo de vida**: `{stage}`"
        if stage == "production":
            open_changes = [c for c in changes if c.get("status") == "open"]
            if open_changes:
                c = open_changes[0]
                criteria = "\n".join(f"  - {_as_data(x)}" for x in c.get("criteria", []))
                change_section = (
                    "\n## Cambio activo (mantenimiento)\n\n"
                    f"- **ID**: {_as_data(c.get('id'))}\n"
                    f"- **Tier de rigor**: `{_as_data(c.get('tier'))}`\n"
                    f"- **Resumen**: {_as_data(c.get('summary'))}\n"
                    f"- **Criterios**:\n{criteria}\n\n---\n"
                )
            else:
                change_section = "\n## Cambio activo (mantenimiento)\n\n[ninguno]\n\n---\n"

    active_desc_line = f"- **Descripción**: {active_desc}".rstrip()

    core_content = f"""{BANNER}
# {project} — Estado de Sesión

> Fuente única de continuidad. Leer al inicio de cada sesión con `/arrancar`.
> Actualizado por: `state_manager.py` (Proyección de `03_project_state.json`)
> Estado completo: `03_project_state.json` | Bugs completos: `06_bug_fixes.md` | Scope: `04_active_scope.md`

---

## Proyecto

- **Fase**: {phase}
- **Última actualización**: {now_iso}
- **Último evento**: {last_step}
- **Foco activo**: {focus_label}{lifecycle_line}
- {counts_line}

---
{change_section}
## Módulo activo

- **ID**: {active_mod}
- **Estado**: `{status}`
- **Tier de rigor**: `{tier}`
{active_desc_line}

---

## Siguiente

> Bloque de cierre de turno (`.agent/skills/decision_translation_core.md`, FW-141/142). Única línea copiable.

{next_line}

---

## Migraciones de framework

{framework_migrations_block}

---

## ACs del módulo activo

{acs_text}

---

## Bloqueadores activos

{blockers_str}

---

## Próximo módulo

{next_module_block}
"""
    return "\n".join(line.rstrip() for line in core_content.splitlines()) + "\n"


def render(state_data: dict) -> None:
    for p in (state_core.CORE_FILE_PATH, state_core.BUGS_FILE_PATH,
              state_core.CLARIFICATIONS_FILE_PATH, state_core.DECISIONS_FILE_PATH):
        _assert_safe_to_write(p)

    _pending: list = []  # (path, content) — se publica todo al final (C5)

    project = state_data.get("project", "[NOMBRE_PROYECTO]")
    now_iso = _now_iso()

    # FW-225: modo mantenimiento. Solo se proyecta si el proyecto declaró su
    # ciclo de vida: los adoptantes que no lo usan conservan core.md intacto.
    lifecycle = state_data.get("lifecycle") if isinstance(state_data.get("lifecycle"), dict) else None
    changes = [c for c in (state_data.get("changes") or []) if isinstance(c, dict)]
    if lifecycle or changes:
        log_path = state_core.STATE_FILE_PATH.parent / "24_change_log.md"
        _assert_safe_to_write(log_path)
        rows = [
            f"| {_as_data(c.get('id'))} | {_as_data((c.get('closed_at') or c.get('opened_at') or '')[:10])} "
            f"| {_as_data(c.get('status'))} | {_as_data(c.get('tier'))} "
            f"| {_as_data(c.get('changelog') or c.get('summary'))} |"
            for c in reversed(changes)
        ]
        log_content = "\n".join([
            BANNER,
            f"# Registro de cambios en mantenimiento — {project}",
            "",
            "> Proyección de `03_project_state.json → changes` (FW-225). Un cambio escalado",
            "> continúa como módulo con el flujo completo.",
            "",
            "| ID | Fecha | Estado | Tier | Cambio |",
            "|---|---|---|---|---|",
            *(rows or ["| — | — | — | — | sin cambios registrados |"]),
            "",
        ])
        _pending.append((log_path, log_content))

    core_content = render_core_markdown(state_data, now_iso=now_iso, workspace_root=state_core.WORKSPACE_ROOT)
    _pending.append((state_core.CORE_FILE_PATH, core_content))

    bug_lines = [
        BANNER,
        f"# Bug Fixes — {project}",
        "",
        "## Formato de entrada",
        "```",
        "### BUG-XXX — [Título breve]",
        "- **Módulo:** [nombre del módulo]",
        "- **Síntoma:** [Lo que el usuario observa]",
        "- **Causa raíz:** [Por qué ocurre]",
        "- **Severidad:** Crítico | Mayor | Menor",
        "- **affects_ac:** true | false",
        "- **Fix:** [Qué se cambió]",
        "- **Archivos afectados:** [lista]",
        "- **Estado:** Abierto | Resuelto",
        "```",
        "",
        "---",
        ""
    ]
    for b in sorted(state_data.get("_bugs", []), key=lambda x: x.get("id", "")):
        aff = "true" if b.get("affects_ac") else "false"
        files = ", ".join(b.get("affected_files", []))
        bug_lines.extend([
            f"### {b['id']} — {_as_data(b['description'])}",
            f"- **Módulo:** {b['module_id']}",
            f"- **Síntoma:** [Reportado en el registro]",
            f"- **Causa raíz:** [En diagnóstico]" if b["status"] == "Abierto" else "- **Causa raíz:** [Resuelto]",
            f"- **Severidad:** {b['severity']}",
            f"- **affects_ac:** {aff}",
            f"- **Fix:** {_as_data(b['fix'])}",
            f"- **Archivos afectados:** [{files}]",
            f"- **Estado:** {b['status']}",
        ])
        # Ronda de revisión final (hallazgo 5): `amend_bug` (FW-122) deja
        # rastro en `bug["amendments"]`, pero la vista de solo lectura no lo
        # mostraba — un agente que siguiera la Regla 2 (nunca leer el JSON
        # crudo) no podía ver qué decía el bug antes de la corrección.
        if b.get("amendments"):
            bug_lines.append("- **Enmiendas:**")
            for a in b["amendments"]:
                campos = ", ".join(sorted(a.get("previous", {})))
                bug_lines.append(
                    f"  - {a.get('at', '?')} — {a.get('reason', '')} "
                    f"(campos previos: {campos})"
                )
        bug_lines.append("")
    _pending.append((state_core.BUGS_FILE_PATH, "\n".join(bug_lines)))

    clar_lines = [
        BANNER,
        f"# Clarificaciones Pendientes — {project}",
        "",
        "> Preguntas abiertas al cliente que bloquean módulos.",
        "",
        "## Formato de entrada",
        "```",
        "### CLAR-XXX — [Pregunta breve]",
        "- **blocked_scope:** [módulo o tarea]",
        "- **blocks_start:** true | false",
        "- **blocks_implementation:** true | false",
        "- **blocks_closure:** true | false",
        "- **blocking_condition:** [condición]",
        "- **Pregunta:** [descripción]",
        "- **Opciones conocidas:** [alternativas]",
        "- **Impacto si no se resuelve:** [impacto]",
        "- **Estado:** Abierta | Resuelta",
        "- **Respuesta:** [respuesta]",
        "```",
        "",
        "---",
        ""
    ]
    for c in sorted(state_data.get("_clarifications", []), key=lambda x: x.get("id", "")):
        clar_lines.extend([
            f"### {c['id']} — {c['title']}",
            f"- **blocked_scope:** {c['blocked_scope']}",
            f"- **blocks_start:** {'true' if c['blocks_start'] else 'false'}",
            f"- **blocks_implementation:** {'true' if c['blocks_implementation'] else 'false'}",
            f"- **blocks_closure:** {'true' if c['blocks_closure'] else 'false'}",
            f"- **blocking_condition:** {c['blocking_condition']}",
            f"- **Pregunta:** {c['question']}",
            f"- **Opciones conocidas:** {c['options']}",
            f"- **Impacto si no se resuelve:** {c['impact']}",
            f"- **Estado:** {c['status']}",
            f"- **Respuesta:** {c['answer']}",
            ""
        ])
    _pending.append((state_core.CLARIFICATIONS_FILE_PATH, "\n".join(clar_lines)))

    dec_lines = [
        BANNER,
        f"# Decisiones Arquitectónicas — {project}",
        "",
        "> Se carga bajo demanda: solo en `/validate-arch` o durante debugging.",
        "> NO leer en arranque.",
        "",
        "---",
        ""
    ]
    for d in sorted(state_data.get("_decisions", []), key=lambda x: x.get("id", "")):
        dec_lines.extend([
            f"### {d['id']} — {d['title']}",
            f"**Fecha:** {d['date']}",
            f"**Estado:** {d['status']}",
        ])
        # Ronda de revisión final (hallazgo 5): una ADR `Superseded`
        # (FW-125) no mostraba quién la reemplazó ni por qué — un agente que
        # siguiera la Regla 2 no podía saber cuál manda sin abrir el JSON.
        if d.get("status") == "Superseded":
            dec_lines.append(f"**Superseded por:** {d.get('superseded_by', '?')}")
            if d.get("supersede_reason"):
                dec_lines.append(f"**Motivo:** {d['supersede_reason']}")
        dec_lines.extend([
            f"**Módulo afectado:** {d['module_id']}",
            "",
            "**Contexto:**",
            f"{d['context']}",
            "",
            "**Opciones consideradas:**",
            f"{d.get('alternatives', '1. Única opción viable analizada.')}",
            "",
            "**Decisión:**",
            f"{d['decision']}",
            "",
            "**Consecuencias:**",
            f"{d.get('consequences', '- Ninguna consecuencia crítica declarada.')}",
            "",
            f"**Fundada en (expertise):** {d['expertise']}" if d.get("expertise") else "",
            "",
            "---",
            ""
        ])
    _pending.append((state_core.DECISIONS_FILE_PATH, "\n".join(dec_lines)))

    brief = expected_session_brief(state_data, generated_at=now_iso)
    try:  # FW-296: sin cambios fuera de `generated_at` no se reescribe (los arneses guardan cada diff)
        previous = json.loads(state_core.SESSION_BRIEF_PATH.read_text(encoding="utf-8"))
        unchanged = {**previous, "generated_at": now_iso} == json.loads(json.dumps(brief, ensure_ascii=False))
    except (OSError, ValueError, TypeError):
        unchanged = False
    if not unchanged:
        _pending.append((state_core.SESSION_BRIEF_PATH,
                         json.dumps(brief, indent=2, ensure_ascii=False, sort_keys=True) + "\n"))

    # Publicación en dos fases: todas las vistas se construyeron sin tocar
    # disco; ahora se publican con escritura atómica cada una. Un fallo de
    # CONSTRUCCIÓN ya no deja proyecciones parcialmente actualizadas.
    #
    # TL FW-018 / BOTÓN FW-082: varios campos interpolados pueden estar
    # vacíos (options/impact/fix sin completar todavía), y una línea como
    # "- **Fix:** {valor}" con valor="" deja un espacio colgando tras los
    # dos puntos — rompe `git diff --check` en cada commit que toque la
    # proyección. rstrip() por línea (no del bloque completo, para no tocar
    # líneas en blanco intencionales) es un choke-point único que protege
    # TODAS las proyecciones generadas, no solo bugs/clarificaciones.
    for _path, _content in _pending:
        _content = "\n".join(line.rstrip() for line in _content.split("\n"))
        _atomic_write(_path, _content)


def _parse_field(block: str, label: str, default: str = "") -> str:
    m = re.search(rf"(?mi)^- \*\*{re.escape(label)}:\*\*\s*(.+)$", block)
    return m.group(1).strip() if m else default


def _first_word(raw: str) -> str:
    """Primera palabra alfabética de `raw`, ignorando decoración markdown
    (**, _, `) y texto posterior. Para campos de estado escritos como
    `**Resuelta** (2026-06-07) — ver ADR-011` o `Aceptada (resuelve …)`, donde
    el importer debe quedarse solo con el token canónico del estado (FW-032)."""
    m = re.search(r"[A-Za-zÁÉÍÓÚÜáéíóúüñÑ]+", raw)
    return m.group(0) if m else ""


def _normalize_status(raw: str, valid: tuple[str, ...], default: str) -> str:
    """Mapea un valor de estado posiblemente decorado al enum canónico."""
    word = _first_word(raw)
    for value in valid:
        if word.lower() == value.lower():
            return value
    return default


def _parse_bool(block: str, label: str, default: bool = False) -> bool:
    """Boolean por la PRIMERA palabra del valor (FW-035). El bug: el viejo
    `_parse_field(...).lower() == "true"` convertía `true para M1 (...)` en
    False, desarmando silenciosamente un gate de cierre (`blocks_closure`).
    Ahora el matiz textual de cola ya no degrada el flag."""
    raw = _parse_field(block, label, "")
    if not raw:
        return default
    word = _first_word(raw).lower()
    if word in ("true", "sí", "si", "yes", "verdadero"):
        return True
    if word in ("false", "no"):
        return False
    return default


_ADR_LABELS = (
    "Fecha", "Estado", "Módulo afectado", "Contexto",
    "Opciones consideradas", "Decisión", "Consecuencias",
)


def _parse_labeled_fields(block: str, labels: tuple[str, ...]) -> dict[str, str]:
    """Extrae {label: valor} de un bloque markdown (FW-035). Tolera el guion
    opcional (`- **L:**` o `**L:**`, este último el que produce render() para
    los ADR) y valores inline o de cuerpo multilínea debajo. El valor de cada
    etiqueta abarca desde su declaración hasta la siguiente etiqueta CANÓNICA de
    `labels` —no cualquier `**x:**`, para no cortar en sub-etiquetas del cuerpo—
    o el fin del bloque; el separador horizontal final (`---`) no se filtra."""
    label_alt = "|".join(re.escape(l) for l in labels)
    pattern = re.compile(rf"(?mi)^[ \t]*(?:- )?\*\*({label_alt}):\*\*[ \t]*(.*)$")
    matches = list(pattern.finditer(block))
    out: dict[str, str] = {}
    for i, m in enumerate(matches):
        matched = m.group(1)
        canon = next((l for l in labels if l.lower() == matched.lower()), matched)
        inline = m.group(2).strip()
        body_end = matches[i + 1].start() if i + 1 < len(matches) else len(block)
        body = block[m.end():body_end].strip()
        value = "\n".join(part for part in (inline, body) if part)
        value = re.sub(r"\n*-{3,}\s*$", "", value).strip()
        out[canon] = value
    return out


def _stamp_if_recognized(path, text: str, recognized: int) -> None:
    """FW-093 (Example Tool): estampar el banner SOLO si el archivo aportó ≥1 entrada
    en formato reconocido (o está efectivamente vacío). Un archivo con contenido
    manual que el parser no entiende NO se estampa: el banner lo marcaría como
    autogenerado y el siguiente render() lo sobrescribiría desde el estado,
    destruyendo la historia manual en silencio. En ese caso se advierte y el
    guard de render() sigue protegiendo el archivo."""
    if BANNER in text:
        return
    has_content = bool(text.strip())
    if recognized > 0 or not has_content:
        path.write_text(BANNER + "\n" + text, encoding="utf-8")
        return
    print(
        f"ADVERTENCIA: {path} tiene contenido manual en formato no reconocido "
        f"(0 entradas importadas de este archivo); NO se estampa el banner de "
        f"autogenerado. Convierte las entradas al formato canónico "
        f"(### BUG-NNN / ### CLAR-NNN / ### ADR-NNN) antes de reimportar, o "
        f"archívalo aparte — un render() ahora lo habría sobrescrito.",
        file=sys.stderr,
    )


def collect_markdown_entities(state_data: dict | None = None) -> dict:
    """Parsea archivos markdown de bugs, clarificaciones y decisiones existentes.

    Idempotente si se proporciona state_data: omite IDs ya existentes en él.
    Estampa banner de advertencia (<!-- CANONICAL SOURCE: ... -->) con
    guard — solo cuando el archivo contiene entradas en formato reconocido
    (FW-093). Devuelve dict con {"bugs": [...], "clarifications": [...], "decisions": [...]}.
    """
    bugs_to_import: list[dict] = []
    existing_bug_ids = {b["id"] for b in state_data.get("_bugs", []) if isinstance(b, dict) and "id" in b} if state_data else set()
    if state_core.BUGS_FILE_PATH.exists():
        text = state_core.BUGS_FILE_PATH.read_text(encoding="utf-8")
        recognized_bugs = 0
        for m in re.finditer(r"(?ms)^### (BUG-\d+) — (.+?)\n(.*?)(?=^### |\Z)", text):
            bug_id, title, block = m.group(1), m.group(2).strip(), m.group(3)
            recognized_bugs += 1
            if bug_id in existing_bug_ids:
                continue
            sev = _parse_field(block, "Severidad", "Menor")
            if sev not in ("Crítico", "Mayor", "Menor"):
                sev = "Menor"
            status = _parse_field(block, "Estado", "Abierto")
            status = status if status in ("Abierto", "Resuelto", "Deuda Técnica") else "Abierto"
            bugs_to_import.append({
                "id": bug_id,
                "module_id": _parse_field(block, "Módulo", "desconocido"),
                "severity": sev,
                "description": title,
                "affects_ac": _parse_bool(block, "affects_ac", False),
                "status": status,
                "fix": _parse_field(block, "Fix", ""),
                "affected_files": [],
            })
            existing_bug_ids.add(bug_id)
        _stamp_if_recognized(state_core.BUGS_FILE_PATH, text, recognized_bugs)

    clars_to_import: list[dict] = []
    existing_clar_ids = {c["id"] for c in state_data.get("_clarifications", []) if isinstance(c, dict) and "id" in c} if state_data else set()
    if state_core.CLARIFICATIONS_FILE_PATH.exists():
        text = state_core.CLARIFICATIONS_FILE_PATH.read_text(encoding="utf-8")
        recognized_clars = 0
        for m in re.finditer(r"(?ms)^### (CLAR-\d+) — (.+?)\n(.*?)(?=^### |\Z)", text):
            cid, title, block = m.group(1), m.group(2).strip(), m.group(3)
            recognized_clars += 1
            if cid in existing_clar_ids:
                continue
            status = _normalize_status(_parse_field(block, "Estado", "Abierta"), ("Abierta", "Resuelta"), "Abierta")
            clars_to_import.append({
                "id": cid, "title": title,
                "blocked_scope": _parse_field(block, "blocked_scope", "desconocido"),
                "blocks_start": _parse_bool(block, "blocks_start", False),
                "blocks_implementation": _parse_bool(block, "blocks_implementation", False),
                "blocks_closure": _parse_bool(block, "blocks_closure", False),
                "blocking_condition": _parse_field(block, "blocking_condition", ""),
                "question": _parse_field(block, "Pregunta", title),
                "options": _parse_field(block, "Opciones conocidas", ""),
                "impact": _parse_field(block, "Impacto si no se resuelve", ""),
                "status": status if status in ("Abierta", "Resuelta") else "Abierta",
                "answer": _parse_field(block, "Respuesta", ""),
            })
            existing_clar_ids.add(cid)
        _stamp_if_recognized(state_core.CLARIFICATIONS_FILE_PATH, text, recognized_clars)

    decs_to_import: list[dict] = []
    existing_dec_ids = {d["id"] for d in state_data.get("_decisions", []) if isinstance(d, dict) and "id" in d} if state_data else set()
    if state_core.DECISIONS_FILE_PATH.exists():
        text = state_core.DECISIONS_FILE_PATH.read_text(encoding="utf-8")
        recognized_decs = 0
        for m in re.finditer(r"(?ms)^### (ADR-\d+) — (.+?)\n(.*?)(?=^### |\Z)", text):
            did, title, block = m.group(1), m.group(2).strip(), m.group(3)
            recognized_decs += 1
            if did in existing_dec_ids:
                continue
            # FW-035: parsear el ADR de verdad (cabecera sin guion + cuerpos
            # multilínea que produce render()) en vez de hardcodear "[importado]".
            fields = _parse_labeled_fields(block, _ADR_LABELS)
            decs_to_import.append({
                "id": did, "title": title,
                "date": fields.get("Fecha", ""),
                "status": _first_word(fields.get("Estado", "")) or "Aceptada",
                "module_id": fields.get("Módulo afectado", "") or "framework",
                "context": fields.get("Contexto", "") or "[importado]",
                "decision": fields.get("Decisión", "") or "[importado]",
                "alternatives": fields.get("Opciones consideradas", ""),
                "consequences": fields.get("Consecuencias", ""),
            })
            existing_dec_ids.add(did)
        _stamp_if_recognized(state_core.DECISIONS_FILE_PATH, text, recognized_decs)

    return {
        "bugs": bugs_to_import,
        "clarifications": clars_to_import,
        "decisions": decs_to_import,
    }


def import_markdown(state_data: dict) -> int:
    """Parse existing bug/clar/decision .md files into the state arrays.
    Idempotent: skips ids already present. Stamps imported files with the
    autogenerated banner so a subsequent render() call will not trigger the
    guard — solo cuando el archivo contiene entradas en formato reconocido
    (FW-093). Returns number of records imported."""
    entities = collect_markdown_entities(state_data)
    bugs = state_data.setdefault("_bugs", [])
    clars = state_data.setdefault("_clarifications", [])
    decs = state_data.setdefault("_decisions", [])

    bugs.extend(entities["bugs"])
    clars.extend(entities["clarifications"])
    decs.extend(entities["decisions"])

    return len(entities["bugs"]) + len(entities["clarifications"]) + len(entities["decisions"])
